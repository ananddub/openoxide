use rustploy_todo_test::{controller::todo_live, models::Todo};
use std::{fs, path::PathBuf};

fn main() {
    let subscription = todo_live::list_subscription().expect("generate live subscription");
    let output = format!(
        r#"// @generated by `cargo run -p rustploy-todo-test --bin generate_live`; do not edit.
import {{createLiveHook}} from '../runtime';

export type Todo = {todo};

export const useTodos = createLiveHook<[], Todo[]>({{
  namespace: {namespace:?},
  endpoint: {endpoint:?},
  event: {event:?},
}});
"#,
        todo = Todo::TYPESCRIPT,
        namespace = subscription.namespace(),
        endpoint = subscription.endpoint(),
        event = subscription.event(),
    );
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("react/src/generated/todo-live.ts");
    fs::create_dir_all(path.parent().unwrap()).expect("create generated directory");
    fs::write(&path, output).expect("write generated live client");
    println!("generated {}", path.display());
}
