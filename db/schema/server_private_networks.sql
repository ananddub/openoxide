CREATE TABLE server_private_networks (
    server_id BIGINT NOT NULL PRIMARY KEY AUTOINCREMENT,
    connection_mode TEXT NOT NULL,
    provider TEXT,
    private_host TEXT,
    tunnel_address TEXT,
    public_key TEXT,
    endpoint TEXT,
    listen_port BIGINT,
    persistent_keepalive BIGINT,
    status TEXT NOT NULL,
    last_handshake_at BIGINT,
    config_version BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    dns_name TEXT,
    routes TEXT NOT NULL,
    health_status TEXT NOT NULL,
    health_error TEXT,
    last_health_check_at BIGINT,
    consecutive_failures BIGINT NOT NULL,
    operation TEXT,
    operation_lease_until BIGINT,
    config_hash TEXT,
    rotation_state TEXT NOT NULL
);
