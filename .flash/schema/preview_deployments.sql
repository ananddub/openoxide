    status TEXT NOT NULL,
    domain TEXT NOT NULL,
    last_deployment_id INTEGER,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL,
    source_owner TEXT,
    source_repository TEXT
);
